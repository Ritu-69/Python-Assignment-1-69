# 1. Camel Case: First word is lowercase, subsequent words are capitalized
studentName = "Aarav"

# 2. Pascal Case: Every word starts with a capital letter
StudentAge = 16

# 3. Snake Case: Words are separated by underscores (standard in Python)
student_grade = "11th"

# 4. Upper Snake Case (SCREAMING_SNAKE_CASE): Used for constants
SCHOOL_NAME = "Sunrise Public School"

# Displaying the values of all variables
print("Camel Case (studentName):", studentName)
print("Pascal Case (StudentAge):", StudentAge)
print("Snake Case (student_grade):", student_grade)
print("Upper Snake Case (SCHOOL_NAME):", SCHOOL_NAME)
