# Demonstrating abs(), round(), and pow() functions

# 1. abs() - Returns the absolute (positive) value of a number
num1 = -25.75
print("Absolute value of -25.75:", abs(num1))

# 2. round() - Rounds a floating-point number to a specified number of decimals
num2 = 3.14159
print("Rounded to nearest integer:", round(num2))
print("Rounded to 2 decimal places:", round(num2, 2))

# 3. pow() - Returns the value of x raised to the power of y (x^y)
base = 2
exponent = 4
print("2 raised to the power 4:", pow(base, exponent))
