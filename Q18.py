# Volume of a Cube
side = float(input("Enter the side of the cube: "))
cube_volume = side ** 3
print("Volume of the cube:", cube_volume)

# Volume of a Cuboid
length = float(input("\nEnter the length of the cuboid: "))
breadth = float(input("Enter the breadth of the cuboid: "))
height = float(input("Enter the height of the cuboid: "))
cuboid_volume = length * breadth * height
print("Volume of the cuboid:", cuboid_volume)
