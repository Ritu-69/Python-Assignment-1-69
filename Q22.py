# Creating variables of different data types
num_int = 25                  # Integer
num_float = 12.5              # Float
text_str = "Hello, Python!"   # String
is_valid = True               # Boolean
fruits_list = ["apple", "banana", "cherry"]  # List
colors_tuple = ("red", "green", "blue")      # Tuple
student_dict = {"name": "Amit", "age": 16}   # Dictionary

# Displaying the data type of each variable using type()
print("Data type of num_int:", type(num_int))
print("Data type of num_float:", type(num_float))
print("Data type of text_str:", type(text_str))
print("Data type of is_valid:", type(is_valid))
print("Data type of fruits_list:", type(fruits_list))
print("Data type of colors_tuple:", type(colors_tuple))
print("Data type of student_dict:", type(student_dict))
