# 1. Integer (int) - whole numbers
age = 25

# 2. Float (float) - decimal numbers
price = 99.95

# 3. Complex (complex) - numbers with real and imaginary parts
complex_num = 3 + 4j

# 4. String (str) - sequence of characters
greeting = "Hello, World!"

# 5. Boolean (bool) - True or False values
is_active = True

# Printing values and their data types using type()
print("Value:", age, "| Data Type:", type(age))
print("Value:", price, "| Data Type:", type(price))
print("Value:", complex_num, "| Data Type:", type(complex_num))
print("Value:", greeting, "| Data Type:", type(greeting))
print("Value:", is_active, "| Data Type:", type(is_active))
