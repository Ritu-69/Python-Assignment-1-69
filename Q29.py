# Define a set (or list/tuple) of numerical values
numbers = {15, 42, 8, 93, 27, 4, 61}

# Find the minimum and maximum values using built-in functions
minimum_value = min(numbers)
maximum_value = max(numbers)

# Display the results
print("Set of numbers:", numbers)
print("Minimum value:", minimum_value)
print("Maximum value:", maximum_value)
