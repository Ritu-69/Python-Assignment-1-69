# Create a dictionary with countries as keys and capitals as values
countries_capitals = {
    "India": "New Delhi",
    "Japan": "Tokyo",
    "France": "Paris",
    "Brazil": "Brasilia",
    "Australia": "Canberra"
}

# Print the entire dictionary
print("Countries and their Capitals:")
for country, capital in countries_capitals.items():
    print(f"{country}: {capital}")
