# Creating variables of different data types
integer_var = 42                      # int (Integer)
float_var = 3.14                      # float (Floating-point number)
string_var = "Hello, Python!"         # str (String)
boolean_var = True                    # bool (Boolean)
list_var = [1, 2, 3, 4]               # list (List)
tuple_var = ("apple", "banana")       # tuple (Tuple)
dict_var = {"name": "Alice", "age": 25} # dict (Dictionary)

# Displaying the values and their data types
print("Integer Value:", integer_var, "| Type:", type(integer_var))
print("Float Value:", float_var, "| Type:", type(float_var))
print("String Value:", string_var, "| Type:", type(string_var))
print("Boolean Value:", boolean_var, "| Type:", type(boolean_var))
print("List Value:", list_var, "| Type:", type(list_var))
print("Tuple Value:", tuple_var, "| Type:", type(tuple_var))
print("Dictionary Value:", dict_var, "| Type:", type(dict_var))
